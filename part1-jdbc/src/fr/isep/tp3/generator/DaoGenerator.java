package fr.isep.tp3.generator;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/*
 * Partie V (bonus) : générateur de POJO et de DAO à partir du dictionnaire de données.
 *  V.1 : liste des colonnes via la vue information_schema.columns
 *  V.2 / V.3 : génération d'une classe Java (POJO) par table
 *  V.4 : génération d'un DAO par table (méthode find implémentée)
 */
public class DaoGenerator {

    static final String PACKAGE = "fr.isep.tp3.generated";

    record Column(String name, String sqlType, boolean pk) {
    }

    public static void main(String[] args) throws SQLException, IOException {
        Path outDir = Paths.get(args.length > 0 ? args[0] : "generated");
        try (Connection c = DriverManager.getConnection("jdbc:postgresql://localhost/isep", "postgres", "postgres")) {
            Map<String, List<Column>> tables = readDictionary(c);

            // V.1 : affichage du dictionnaire
            for (Map.Entry<String, List<Column>> t : tables.entrySet()) {
                System.out.println("TABLE " + t.getKey());
                for (Column col : t.getValue()) {
                    System.out.printf("   %-10s %-20s %s%n", col.name(), col.sqlType(), col.pk() ? "PK" : "");
                }
            }

            // V.3 et V.4 : génération des fichiers
            Path pkgDir = outDir.resolve(PACKAGE.replace('.', '/'));
            Files.createDirectories(pkgDir);
            for (Map.Entry<String, List<Column>> t : tables.entrySet()) {
                String className = capitalize(t.getKey());
                Path pojo = pkgDir.resolve(className + ".java");
                Files.writeString(pojo, generatePojo(className, t.getValue()));
                Path dao = pkgDir.resolve(className + "DAO.java");
                Files.writeString(dao, generateDao(className, t.getKey(), t.getValue()));
                System.out.println("Generated " + pojo + " and " + dao);
            }
        }
    }

    static Map<String, List<Column>> readDictionary(Connection c) throws SQLException {
        String sql = "SELECT c.table_name, c.column_name, c.data_type, "
                + "  (SELECT count(*) FROM information_schema.key_column_usage k "
                + "     JOIN information_schema.table_constraints tc ON tc.constraint_name = k.constraint_name "
                + "    WHERE tc.constraint_type = 'PRIMARY KEY' AND k.table_name = c.table_name "
                + "      AND k.column_name = c.column_name) AS is_pk "
                + "FROM information_schema.columns c "
                + "WHERE c.table_schema = ? ORDER BY c.table_name, c.ordinal_position";
        Map<String, List<Column>> tables = new LinkedHashMap<>();
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, "public");
            try (ResultSet rs = ps.executeQuery()) {
                while (rs.next()) {
                    tables.computeIfAbsent(rs.getString("table_name"), k -> new ArrayList<>())
                            .add(new Column(rs.getString("column_name"), rs.getString("data_type"), rs.getInt("is_pk") > 0));
                }
            }
        }
        return tables;
    }

    static String javaType(String sqlType) {
        switch (sqlType) {
            case "integer":
            case "smallint":
                return "Integer";
            case "bigint":
                return "Long";
            case "numeric":
                return "java.math.BigDecimal";
            case "date":
                return "java.sql.Date";
            case "timestamp without time zone":
                return "java.sql.Timestamp";
            case "boolean":
                return "Boolean";
            default:
                return "String";
        }
    }

    static String generatePojo(String className, List<Column> cols) {
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(PACKAGE).append(";\n\n");
        sb.append("/* Generated by DaoGenerator - do not edit */\n");
        sb.append("public class ").append(className).append(" {\n\n");
        for (Column col : cols) {
            sb.append("    private ").append(javaType(col.sqlType())).append(' ').append(col.name()).append(";\n");
        }
        for (Column col : cols) {
            String type = javaType(col.sqlType());
            String cap = capitalize(col.name());
            sb.append("\n    public ").append(type).append(" get").append(cap).append("() {\n")
              .append("        return ").append(col.name()).append(";\n    }\n");
            sb.append("\n    public void set").append(cap).append('(').append(type).append(' ').append(col.name()).append(") {\n")
              .append("        this.").append(col.name()).append(" = ").append(col.name()).append(";\n    }\n");
        }
        sb.append("\n    @Override\n    public String toString() {\n        return \"").append(className).append("{\"");
        for (int i = 0; i < cols.size(); i++) {
            String n = cols.get(i).name();
            sb.append("\n                + \"").append(i > 0 ? ", " : "").append(n).append("=\" + ").append(n);
        }
        sb.append("\n                + \"}\";\n    }\n}\n");
        return sb.toString();
    }

    static String generateDao(String className, String table, List<Column> cols) {
        Column pk = cols.stream().filter(Column::pk).findFirst().orElse(cols.get(0));
        StringBuilder sb = new StringBuilder();
        sb.append("package ").append(PACKAGE).append(";\n\n");
        sb.append("import fr.isep.tp3.dao.DAO;\n\nimport java.sql.*;\n\n");
        sb.append("/* Generated by DaoGenerator - do not edit */\n");
        sb.append("public class ").append(className).append("DAO extends DAO<").append(className).append("> {\n\n");
        sb.append("    public ").append(className).append("DAO(Connection connect) {\n        super(connect);\n    }\n\n");
        sb.append("    @Override\n    public ").append(className).append(" find(int id) {\n");
        sb.append("        String sql = \"SELECT * FROM ").append(table).append(" WHERE ").append(pk.name()).append(" = ?\";\n");
        sb.append("        try (PreparedStatement ps = connect.prepareStatement(sql)) {\n");
        sb.append("            ps.setInt(1, id);\n");
        sb.append("            try (ResultSet rs = ps.executeQuery()) {\n");
        sb.append("                if (!rs.next()) return null;\n");
        sb.append("                ").append(className).append(" o = new ").append(className).append("();\n");
        for (Column col : cols) {
            sb.append("                o.set").append(capitalize(col.name())).append("((")
              .append(javaType(col.sqlType())).append(") rs.getObject(\"").append(col.name()).append("\"));\n");
        }
        sb.append("                return o;\n            }\n        } catch (SQLException e) {\n");
        sb.append("            e.printStackTrace();\n            return null;\n        }\n    }\n\n");
        for (String m : new String[]{"create", "update", "delete"}) {
            sb.append("    @Override\n    public boolean ").append(m).append('(').append(className)
              .append(" object) {\n        throw new UnsupportedOperationException(\"TODO\");\n    }\n\n");
        }
        sb.append("}\n");
        return sb.toString();
    }

    static String capitalize(String s) {
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }
}
