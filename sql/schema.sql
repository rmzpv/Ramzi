-- Schéma EMP / DEPT utilisé pour le TP 3 (PostgreSQL)
DROP TABLE IF EXISTS emp;
DROP TABLE IF EXISTS dept;

CREATE TABLE dept (
    deptno  INTEGER PRIMARY KEY,
    dname   VARCHAR(14),
    loc     VARCHAR(13)
);

CREATE TABLE emp (
    empno    INTEGER PRIMARY KEY,
    ename    VARCHAR(10),
    efirst   VARCHAR(10),
    job      VARCHAR(9),
    mgr      INTEGER REFERENCES emp(empno),
    hiredate DATE,
    sal      INTEGER,
    comm     INTEGER,
    tel      VARCHAR(10),
    deptno   INTEGER REFERENCES dept(deptno)
);

